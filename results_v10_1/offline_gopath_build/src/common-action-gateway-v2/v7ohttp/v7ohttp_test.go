package v7ohttp

import (
	"bytes"
	"errors"
	"reflect"
	"testing"
)

func testProfile() PublicProfile {
	return PublicProfile{Name: "STRICT-OHTTP-V7", Sessions: 2, SlotsPerSession: 3,
		RequestEncapsulatedBytes: 1024, ResponseEncapsulatedBytes: 1024,
		RequestDeltaNS: 50_000_000, ResponseLagNS: 25_000_000, PublicLifetimeNS: 300_000_000}
}

func metadata(direction string, slot SlotID) OuterMetadata {
	contentType := RequestContentType
	if direction == "RESPONSE" {
		contentType = ResponseContentType
	}
	return OuterMetadata{RelayEndpoint: "relay.invalid", GatewayEndpoint: "gateway.invalid",
		ConnectionID: "public-connection-1", ContentType: contentType, ContentLength: 1024,
		Profile: "STRICT-OHTTP-V7", Slot: slot}
}

func TestUnavailableBackendFailsClosedAndLegacyIsNotCanonical(t *testing.T) {
	backend := UnavailableBackend{}
	if backend.RFC9458Wire() || backend.Status() != BackendNotImplementedOffline {
		t.Fatal("unavailable backend was promoted to RFC 9458")
	}
	if _, _, err := backend.EncapsulateRequest(SlotID{}, nil); !errors.Is(err, ErrRFC9458Unavailable) {
		t.Fatalf("unexpected error: %v", err)
	}
	legacy := LegacyDevTransport{}
	if legacy.RFC9458Wire() || legacy.Canonical() || RequireCanonical(legacy.Name(), BackendPass, legacy.RFC9458Wire()) == nil {
		t.Fatal("legacy transport entered canonical path")
	}
}

func TestOpaqueRelayForwardsExactBytesAndLogsOnlyPublicMetadata(t *testing.T) {
	relay := OpaqueRelay{Profile: testProfile()}
	body := bytes.Repeat([]byte{0xa5}, 1024)
	var forwarded bytes.Buffer
	if err := relay.ForwardRequest(metadata("REQUEST", SlotID{Session: 1, Slot: 2}), body, &forwarded); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(body, forwarded.Bytes()) {
		t.Fatal("relay changed trusted-generated bytes")
	}
	if len(relay.Observations) != 1 {
		t.Fatal("missing public relay observation")
	}
	fields := reflect.VisibleFields(reflect.TypeOf(RelayObservation{}))
	for _, field := range fields {
		switch field.Name {
		case "Direction", "RelayEndpoint", "GatewayEndpoint", "ConnectionID", "ContentType", "ContentLength", "Profile", "Session", "Slot":
		default:
			t.Fatalf("unexpected relay-visible field: %s", field.Name)
		}
	}
}

func TestRelayRejectsWrongLengthOrContentType(t *testing.T) {
	relay := OpaqueRelay{Profile: testProfile()}
	wrongType := metadata("REQUEST", SlotID{Slot: 1})
	wrongType.ContentType = "application/json"
	if err := relay.ForwardRequest(wrongType, make([]byte, 1024), &bytes.Buffer{}); err == nil {
		t.Fatal("accepted secret-dependent content type")
	}
	if err := relay.ForwardRequest(metadata("REQUEST", SlotID{Slot: 1}), make([]byte, 1023), &bytes.Buffer{}); err == nil {
		t.Fatal("accepted non-fixed body length")
	}
}

func TestLateResultUsesCurrentSlotContextOnly(t *testing.T) {
	result := &PrivateResponse{Status: 1, OperationID: "op-from-slot-1", Payload: []byte("done")}
	selected := SelectForSlot(SlotID{Session: 0, Slot: 3}, result)
	if selected.ContextSlot.Slot != 3 || selected.Result.OperationID != "op-from-slot-1" {
		t.Fatal("application association was confused with OHTTP response context")
	}
}

func TestProfileRequiresFixedSizesAndLifetime(t *testing.T) {
	if err := testProfile().Validate(); err != nil {
		t.Fatal(err)
	}
	bad := testProfile()
	bad.ResponseEncapsulatedBytes = 0
	if bad.Validate() == nil {
		t.Fatal("profile without fixed response size accepted")
	}
}

func TestNoopHasNoPrivateRouteAndOuterMetadataHasNoSemanticFields(t *testing.T) {
	noop := PrivateActionMessage{ProtocolVersion: 1, Kind: ActionNoop, OperationID: []byte("private-op")}
	if err := noop.Validate(); err != nil {
		t.Fatal(err)
	}
	bad := noop
	bad.RouteHandle = []byte("forbidden-route")
	if bad.Validate() == nil {
		t.Fatal("NOOP with real route accepted")
	}
	for _, field := range reflect.VisibleFields(reflect.TypeOf(OuterMetadata{})) {
		switch field.Name {
		case "RelayEndpoint", "GatewayEndpoint", "ConnectionID", "ContentType", "ContentLength", "Profile", "Slot":
		default:
			t.Fatalf("private semantic field escaped to outer metadata: %s", field.Name)
		}
	}
}
